#!/usr/bin/env Rscript
args <- commandArgs(trailingOnly=TRUE)
if (length(args)!=1L || Sys.getenv("NAMPY_REFRESH_REFERENCE_FIXTURES")!="1") stop("Set NAMPY_REFRESH_REFERENCE_FIXTURES=1 and supply output directory")
lib <- Sys.getenv("GAMLSS_LIB_PATH",unset="")
if(nzchar(lib)) .libPaths(c(lib,.libPaths()))
suppressPackageStartupMessages(library(gamlss))
suppressPackageStartupMessages(library(gamlss.dist))
out <- args[[1L]]
dir.create(out,recursive=TRUE,showWarnings=FALSE)
write.csv(data.frame(package=c("R","gamlss","gamlss.dist"),version=c(as.character(getRversion()),as.character(packageVersion("gamlss")),as.character(packageVersion("gamlss.dist")))),file.path(out,"versions.csv"),row.names=FALSE)
mu <- c(.2,.7,1,2,5,3)
sigma <- c(.4,.8,1,1.2,.5,.7)
pi0 <- c(.1,.2,.4,.6,.3,.7)
y <- c(0,.1,1,0,8,2)
probability <- c(.01,.1,.5,.9,.99,.8)
write.csv(data.frame(mu=mu,sigma=sigma,pi0=pi0,y=y,probability=probability,log_prob=dZAGA(y,mu,sigma,pi0,log=TRUE),cdf=pZAGA(y,mu,sigma,pi0),quantile=qZAGA(probability,mu,sigma,pi0)),file.path(out,"probability.csv"),row.names=FALSE)
set.seed(222)
x <- seq(-1,1,length.out=200)
y <- rZAGA(length(x),mu=exp(.4+.3*x),sigma=.55,nu=plogis(-.8+.4*x))
data <- data.frame(x=x,y=y)
fit <- gamlss(y~x,sigma.formula=~1,nu.formula=~x,family=ZAGA(),data=data,control=gamlss.control(n.cyc=1000L,c.crit=1e-10,trace=FALSE))
if(!fit$converged) stop("ZAGA reference failed to converge")
data$mu <- fitted(fit,"mu")
data$sigma <- fitted(fit,"sigma")
data$pi0 <- fitted(fit,"nu")
write.csv(data,file.path(out,"fit.csv"),row.names=FALSE)
