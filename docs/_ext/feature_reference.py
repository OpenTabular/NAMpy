def heading(text, char="="):
    return f"{text}\n{char * len(text)}\n\n"


def write(root, path, content):
    path = root / path
    path.parent.mkdir(parents=True, exist_ok=True)
    content = content.rstrip() + "\n"
    if path.suffix == ".rst":
        content = (
            ".. Generated by docs/_ext/feature_reference.py; edit its authored contracts.\n\n"
            + content
        )
    if not path.exists() or path.read_text() != content:
        path.write_text(content)


def tree(title, entries, intro="", *, related_links=True):
    # A page has one sidebar parent. Existing API guides are related links,
    # rather than duplicate tree entries with ambiguous selected states.
    related = [entry for entry in entries if "</api/" in entry] if related_links else []
    children = [entry for entry in entries if entry not in related]
    text = (
        heading(title)
        + intro
        + "\n\n.. toctree::\n   :maxdepth: 1\n\n"
        + "".join(f"   {entry}\n" for entry in children)
    )
    if related:
        text += "\n" + heading("Related APIs", "-")
        text += "".join(f"* :doc:`{entry}`\n" for entry in related)
    return text


