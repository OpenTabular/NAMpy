def parameters(obj, overrides=None):
    from public_reference import PARAMETER_MEANINGS

    from nampy.neural.configs.nam_config import DefaultNAMConfig
    from nampy.neural.configs.nbm_config import DefaultNBMConfig

    docs = {
        "n_knots": "Number of knots in each learnable spline feature layer; basis width follows the spline construction, not a hidden MLP width.",
        **PARAMETERS,
        **descriptions(DefaultNAMConfig),
        **descriptions(DefaultNBMConfig),
        **PARAMETER_MEANINGS,
        **descriptions(obj),
        **(overrides or {}),
    }
    rows = []
    from dataclasses import is_dataclass

    instance = obj() if inspect.isclass(obj) and is_dataclass(obj) else None
    items = list(inspect.signature(obj).parameters.items())
    if getattr(obj, "__name__", "") in {
        "ShapeConstrainedBSplineTerm",
        "ShapeConstrainedAdaptiveTerm",
    }:
        items = [
            (name, parameter)
            for name, parameter in items
            if parameter.kind is not inspect.Parameter.VAR_KEYWORD
        ]
        present = {name for name, _ in items}
        items += [
            (name, parameter)
            for name, parameter in inspect.signature(obj.__mro__[1]).parameters.items()
            if name not in present
            and parameter.kind is not inspect.Parameter.VAR_KEYWORD
        ]
    for name, p in items:
        if instance is not None and hasattr(instance, name):
            p = p.replace(default=getattr(instance, name))
        if name in {"self", "cls"}:
            continue
        if name not in docs:
            raise ValueError(f"Missing parameter description: {obj}: {name}")
        default = (
            "Required"
            if p.default is inspect.Parameter.empty
            else f"``{literal(p.default)}``"
        )
        if p.kind in {p.VAR_KEYWORD, p.VAR_POSITIONAL}:
            default = "Variable arguments"
        annotation = parameter_type(name, p.default, obj=obj, annotation=p.annotation)
        rows.append((f"``{name}``", f"``{annotation}``", default, docs[name]))
    return (
        "Dimensions: ``n`` rows, ``d`` input columns, ``p`` fitted coefficients, ``q`` response/family output columns; ``n_ref`` is the centering-reference row count.\n\n"
        + table(["Parameter", "Type / input shape", "Default", "Description"], rows)
        if rows
        else "No additional parameters.\n\n"
    )


def signature(obj, name=None):
    value = str(inspect.signature(obj)).replace("\n", " ")
    for parameter in inspect.signature(obj).parameters.values():
        if (
            callable(parameter.default)
            and parameter.default is not inspect.Parameter.empty
        ):
            value = value.replace(repr(parameter.default), literal(parameter.default))
    return (
        heading("Signature", "-")
        + ".. code-block:: python\n\n   "
        + (name or obj.__name__)
        + value
        + "\n\n"
    )


def module_notes(cls):
    """Preserve detailed constructor semantics already authored with the code."""
    module = inspect.getmodule(cls)
    doc = inspect.getdoc(module) or ""
    return (heading("Implementation notes", "-") + doc + "\n\n") if doc else ""


def generate_smooths(root):
    from smooth_contracts import formula_option_rows, smooth_inputs

    import nampy.gam.smooths as smooths
    import nampy.gam.specs  # noqa: F401 - populate formula-only descriptors
    from nampy.gam.basis_registry import basis_descriptors

    entries = []
    runtime_pages = {}
    for d in sorted(basis_descriptors(), key=lambda d: d.name):
        name = d.name
        cls = (
            d.runtime_class
            or {
                "fs": smooths.FSmoothInteractionTerm,
                "sz": smooths.SZSmoothInteractionTerm,
            }[name]
        )
        entries.append(name)
        feature = "x, z" if d.min_features == 2 or name in {"te", "ti", "t2"} else "x"
        if name in {"fs", "sz"}:
            feature = "x, group"
        formula = (
            f"{name}({feature})"
            if name in {"te", "ti", "t2"}
            else f"s({feature}, bs='{name}')"
        )
        if cls.__name__ == "BivariateShapePSplineTerm":
            feature = "x, z"
            formula = f"s({feature}, bs='{name}')"
        covariates = smooth_inputs(d)
        description = SMOOTH_MEANINGS[name]
        text = heading(smooth_title(name, description)) + description + "\n\n"
        text += smooth_theory(name)
        if "shape" in cls.__module__:
            text += "This is a SCAM-style shape-constrained basis. See :doc:`/user_guide/shape_constrained_gams` for its inequalities and supported fitting routes.\n\n"
        text += (
            heading("Formula interface", "-")
            + f'.. code-block:: python\n\n   formula = "y ~ {formula}"\n\n'
        )
        text += "Formula constructors are parsed inside strings; they are not Python functions. ``k``, ``m``, ``by``, ``id``, ``sp`` and ``fx`` configure the term where supported. Formula ``id`` maps to runtime ``smoothing_id`` and ``fx`` maps to ``fixed``.\n\n"
        runtime = signature(cls)
        runtime += f"Runtime class: ``{cls.__module__}.{cls.__name__}``. Shared class defaults may name another variant: pass ``basis='{name}'`` when the constructor exposes ``basis``.\n\n"
        overrides = {
            "full": FAMILY_PARAMETERS["full"],
            **smooth_parameter_meanings(name),
        }
        runtime += heading("Parameters", "-") + parameters(cls, overrides)
        text += heading("Parameters", "-") + table(
            ["Formula option", "Type / shape", "Default", "Meaning"],
            formula_option_rows(d),
        )
        text += "The formula compiler resolves defaults independently of runtime constructors. ``knots`` and ``select`` belong to the model, not the formula call. Runtime-only setup options are documented in the implementation API.\n\n"
        if name in {"te", "ti", "t2"}:
            text += (
                "``bs`` and ``k`` are specified per margin; ``d`` groups covariates into those margins. ``np`` is not implemented by NAMpy's formula compiler."
                + (
                    " ``fx`` is not accepted by t2; use fixed model penalties for supported routes.\n\n"
                    if name == "t2"
                    else "\n\n"
                )
            )
        text += heading("Identifiability, penalty and prediction", "-")
        text += "The basis penalty acts on fitted coefficient coordinates; requested rank k is not fitted EDF. Ordinary smooth centering separates the smooth from the model intercept, subject to the basis, numeric/factor by-variable and point-constraint rules. A point constraint replaces the relevant centering direction rather than fixing an arbitrary coefficient. Prediction reuses the fitted knots, constraints and penalty setup.\n\n"
        if name in {"cr", "cs"}:
            text += "Natural cubic spline tails extend linearly beyond the boundary knots. cs adds null-space shrinkage to the cr roughness penalty. Extrapolation is consequently more restrictive than adding a new spline outside the fitted knot interval.\n\n"
        elif name in {"cc", "cp"}:
            text += "New covariate values use the fitted periodic domain; matching boundary behavior is part of the cyclic construction. The cycle boundaries must represent a real period in the data.\n\n"
        elif name in {"re", "mrf"}:
            text += "Prediction uses fitted region/group levels rather than continuous extrapolation. Random-effect terms give unseen levels zero contribution; MRF terms reject unknown regions.\n\n"
        else:
            text += "Out-of-range behavior is basis-specific and follows the retained fitted basis, rather than automatic expansion of its rank or knot domain. For bounded spatial domains and shape constraints, inspect the domain/constraint restrictions in the runtime notes before extrapolating.\n\n"
        text += heading("Capabilities", "-") + table(
            ["Property", "Value"],
            [
                ("Covariates", covariates),
                ("Tensor marginal", str(d.supports_tensor)),
                ("Point constraints", str(d.supports_pc or name in {"te", "ti", "t2"})),
                (
                    "Additional xt setup",
                    str(d.accepts_xt or name in {"te", "ti", "t2", "fs", "sz"}),
                ),
            ],
        )
        text += (
            heading("Outputs", "-")
            + "The formula adds a term to the fitted model's additive predictor. Its coefficient block has p_term columns after constraints; this dimension differs from EDF. ``predict(type='terms')`` returns a floating array with n rows and one column per retained term for a scalar predictor. ``lpmatrix`` returns the full floating model design, shape (n, p), including the other terms. The scalar Gaussian examples below produce response predictions of shape (n,). Runtime matrix and penalty contracts are documented separately.\n\n"
        )
        if name in {"te", "ti", "t2"}:
            text += "Before identifiability constraints, the tensor has the product of the marginal basis dimensions, not a single k columns. Marginal/term constraints and retained t2 blocks determine the final coefficient count.\n\n"
        text += example_rst(
            root, f"statistical_reference/smooths/{name}", smooth_example(name, cls)
        )
        runtime += (
            heading("Outputs", "-")
            + "``fit(X, feature_names)`` accepts a numeric/categorical design with n rows and its d column names, initializes the term, and returns the same term instance. ``transform_new(X_new)`` returns a floating NumPy array of shape (n_new, p_term) in the fitted constraint coordinates. ``penalties`` is a list of floating square arrays, each (p_term, p_term). Multiplying the design by its coefficient vector gives the link contribution of shape (n_new,). Invalid feature names, dimensions and basis-specific domains raise ValueError; unsupported compositions raise NotImplementedError.\n\n"
            + module_notes(cls)
        )
        default_basis = inspect.signature(cls).parameters.get("basis")
        if cls.__name__ not in runtime_pages or (
            default_basis and default_basis.default == name
        ):
            runtime_pages[cls.__name__] = heading(cls.__name__) + runtime
        if name == "so":
            text += ".. include:: /_includes/soap_domain_details.inc\n\n"
        text += f":doc:`Runtime constructor and implementation notes </extension_reference/smooths/{cls.__name__}>`.\n\n"
        related = (
            {"cr", "cs", "bs", "ps"}
            if name in {"cr", "cs", "bs", "ps"}
            else {"cc", "cp"}
            if name in {"cc", "cp"}
            else {"tp", "ts", "ds", "gp"}
            if name in {"tp", "ts", "ds", "gp"}
            else {"te", "ti", "t2"}
            if name in {"te", "ti", "t2"}
            else {"re", "fs", "sz", "mrf"}
            if name in {"re", "fs", "sz", "mrf"}
            else {"so", "sf", "sw"}
            if name in {"so", "sf", "sw"}
            else set()
        )
        if related - {name}:
            text += (
                heading("Related bases", "-")
                + " · ".join(
                    f":doc:`{other} <{other}>`" for other in sorted(related - {name})
                )
                + "\n\n"
            )

        text += ":doc:`Formula syntax </api/gam_formula>` · :doc:`Smooth overview </api/gam_smooths>` · :doc:`Prediction outputs <../methods/predict>`\n"
        write(root, f"statistical_reference/smooths/{name}.rst", text)
    for class_name, body in runtime_pages.items():
        write(root, f"extension_reference/smooths/{class_name}.rst", body)
    write(
        root,
        "statistical_reference/smooths/index.rst",
        tree(
            "Smooth bases and tensor products",
            entries,
            "Each registered basis has its own page. SCAM shape constraints are included alongside ordinary smooths.",
        ),
    )
    return ["smooths/" + n for n in entries]


def family_sections(root):
    """Reuse precise family-specific scale/likelihood notes, without copying drift."""
    text = (
        Path(__file__).resolve().parents[1] / "_includes/statistical_family_details.inc"
    ).read_text()
    import re

    matches = list(re.finditer(r"^``([^`]+)``\n[~]+\n", text, re.M))
    result = {
        m[1]: text[
            m.end() : matches[i + 1].start() if i + 1 < len(matches) else len(text)
        ]
        for i, m in enumerate(matches)
    }
    titles = {
        "scat": "Scaled Student t family",
        "zip": "Hurdle Poisson family",
        "cnorm": "Censored normal family",
        "clog": "Censored logistic family",
        "cpois": "Censored Poisson family",
        "bcg": "Censored Box-Cox Gaussian family",
    }
    for name, title in titles.items():
        start = text.index(title + "\n")
        body = text.index("\n\n", start) + 2
        following = re.search(r"^.+\n-{4,}\n", text[body:], re.M)
        result[name] = text[body : body + following.start() if following else len(text)]
    return result


